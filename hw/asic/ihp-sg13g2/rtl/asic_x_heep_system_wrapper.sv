// Minimal synthesis wrapper for the standalone Yosys ASIC flow (IHP-SG13G2).
//
// `x_heep_system` cannot be a synthesis top on its own: it exposes six
// SystemVerilog `interface` ports (the CV-X-IF eXtension Interface) that have no
// hardware meaning while unconnected. This wrapper instantiates those interfaces
// as internal objects, ties off every non-pad control port, and re-exports only
// the pad `inout wire`s. It is the toplevel of the `asic_yosys_synthesis` target.
//
// NOTE: the pad list below mirrors `hw/system/x_heep_system.sv` for the default
// configuration (configs/general.hjson). If X_HEEP_CFG changes the padring, this
// file must be updated by hand.

