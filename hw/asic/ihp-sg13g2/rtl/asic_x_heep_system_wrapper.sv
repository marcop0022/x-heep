      .xif_compressed_if,
      .xif_issue_if,
      .xif_commit_if,
      .xif_mem_if,
      .xif_mem_result_if,
      .xif_result_if,

      // tied-off control interface
      .hart_id_i('0),
      .xheep_instance_id_i('0),
      .intr_vector_ext_i('0),
      .intr_ext_peripheral_i(1'b0),
      .ext_xbar_master_req_i('0),
      .ext_xbar_master_resp_o(),
