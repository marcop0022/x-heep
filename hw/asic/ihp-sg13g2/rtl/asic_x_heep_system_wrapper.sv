  if_xif xif_commit_if ();
  if_xif xif_mem_if ();
  if_xif xif_mem_result_if ();
  if_xif xif_result_if ();

  x_heep_system x_heep_system_i (
      // pads
      .clk_i,
      .rst_ni,
